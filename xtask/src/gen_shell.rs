//! `cargo xtask gen-shell`: writes the files in `shell/` from the pinned
//! nvm.sh. `--check` fails when one is out of date.
//!
//! `init.sh` is the text `nvmimic init` prints. It defines every function
//! nvm defines. Small pure-shell ones are copied unchanged, `nvm` keeps nvm's
//! own option handling, and the rest hand their work to the binary through
//! one private function, `__nvmimic_handoff`. Nothing nvm does not have is
//! reachable through the name `nvm`.
//!
//! `nvm.sh` is the file that goes into `$NVM_DIR`. It holds a few lines that
//! run `nvmimic init` and `eval` what it prints.

use std::fs;
use std::process::ExitCode;

/// nvm functions copied unchanged: no external programs, no state. The one
/// that does start programs is `nvm_command_info`, which has to ask the
/// shell itself how it finds a name. Only `nvm debug` uses it.
const VERBATIM: &[&str] = &[
    "nvm_is_zsh",
    "nvm_stdout_is_terminal",
    "nvm_echo",
    "nvm_echo_with_colors",
    "nvm_cd",
    "nvm_err",
    "nvm_err_with_colors",
    "nvm_grep",
    "nvm_has",
    "nvm_has_executable",
    "nvm_has_non_aliased",
    "nvm_is_alias",
    "nvm_command_info",
    "nvm_tree_contains_path",
    "nvm_find_project_dir",
    "nvm_find_up",
    "nvm_find_nvmrc",
    "nvm_version_dir",
    "nvm_alias_path",
    "nvm_hash_reset",
    "nvm_iojs_prefix",
    "nvm_node_prefix",
    "nvm_is_iojs_version",
    "nvm_strip_iojs_prefix",
    "nvm_cache_dir",
    "nvm_is_natural_num",
    "nvm_validate_implicit_alias",
    "nvm_process_parameters",
];

/// The whole of `shell/nvm.sh`, the file `self install` puts into `$NVM_DIR`.
const NVM_SH: &str = r#"# Node Version Manager, as nvmimic provides it.
#
# Other tools look for this file and source it, so it has to exist. It holds
# no code of its own: it asks the nvmimic program for the shell functions and
# runs what the program prints. That starts no program but nvmimic.
#
# This file is generated by `cargo xtask gen-shell`. Edit the generator.
#
# nvmimic is MIT licensed: Copyright (c) 2026 Taylor Silenzio.
# Its first line is taken from nvm (https://github.com/nvm-sh/nvm), MIT
# licensed: Copyright (c) 2010 Tim Caswell, Copyright (c) 2014 Jordan Harband.

# shellcheck disable=SC2039,SC3028
{ # this ensures the entire script is downloaded #

NVM_SCRIPT_SOURCE="${_:-}"

if ! [ -x "@nvmimic-binary@" ]; then
  command printf 'nvm.sh: the nvmimic program is not at %s\nInstall nvmimic again, or delete this file.\n' "@nvmimic-binary@" >&2
  unset NVM_SCRIPT_SOURCE
  return 127
fi

# With `set -x` on, the shell would print every line of the functions it is
# about to be given. Tracing is off for that one line, and the text switches
# it back on before it does anything else.
__nvmimic_trace=''
case "$-" in
  *x*)
    set +x
    __nvmimic_trace=1
  ;;
esac
# The program gets NVM_DIR whether or not it is exported, which shell this
# is, and the path it was started by, which the functions keep using. What
# it prints ends by loading the default version, and this file returns what
# that returned, as nvm's nvm.sh does.
eval "$(NVM_DIR="${NVM_DIR-}" \
  __NVMIMIC_ZSH="${ZSH_VERSION-}" __NVMIMIC_BASH="${BASH_VERSINFO-}" \
  __NVMIMIC_SHELLOPTS="${SHELLOPTS-}" __NVMIMIC_OPTS="$-" \
  __NVMIMIC_ARG0="$0" __NVMIMIC_SOURCE="${BASH_SOURCE-}" \
  __NVMIMIC_PROGRAM="@nvmimic-binary@" command "@nvmimic-binary@" init)" || return $?

# What the program prints unsets this. Still set means it printed nothing.
if [ -n "${__nvmimic_trace+x}" ]; then
  [ -z "${__nvmimic_trace}" ] || set -x
  unset __nvmimic_trace NVM_SCRIPT_SOURCE
  return 1
fi

} # this ensures the entire script is downloaded #
"#;

/// The top of `shell/init.sh`.
const HEADER: &str = r#"# nvmimic's shell functions: what `nvmimic init` prints.
#
# This defines the same shell functions nvm's nvm.sh defines. Small ones are
# copied from nvm unchanged. The rest, `nvm` included, hand their work to
# the nvmimic program through `__nvmimic_handoff`.
#
# Generated by `cargo xtask gen-shell`. Edit the generator.
#
# Parts of this are copied from nvm (https://github.com/nvm-sh/nvm),
# MIT licensed: Copyright (c) 2010 Tim Caswell, Copyright (c) 2014 Jordan Harband.
# nvmimic is MIT licensed: Copyright (c) 2026 Taylor Silenzio.

# shellcheck disable=SC2039,SC2016,SC2001,SC3043
"#;

/// Run by the shell that loads nvmimic, after the functions are defined:
/// tracing goes back on if `nvm.sh` switched it off.
const TRACE_BACK: &str = r#"case "${__nvmimic_trace-}" in
  1)
    unset __nvmimic_trace
    set -x
  ;;
  *) unset __nvmimic_trace ;;
esac
"#;

const AUTO: &str = r#"nvm_auto() {
  case "${1-}" in
    none) return 0 ;;
  esac
  __nvmimic_handoff nvm_auto "$@"
}
"#;

/// The one function in `shell/init.sh` that nvm does not have. Every other
/// function reaches the nvmimic program through it.
const HANDOFF: &str = "__nvmimic_handoff";

/// Whether `shell/init.sh` carries this nvm function's own code.
pub fn is_verbatim(name: &str) -> bool {
    VERBATIM.contains(&name)
}

pub fn run(args: &[&str]) -> ExitCode {
    let check = args.contains(&"--check");
    let mut ok = true;
    for (name, generated) in [
        ("nvm.sh", Ok(NVM_SH.to_string())),
        ("init.sh", generate()),
        ("bash_completion", completion()),
    ] {
        let generated = match generated {
            Ok(text) => text,
            Err(message) => {
                eprintln!("gen-shell: {name}: {message}");
                return ExitCode::FAILURE;
            }
        };
        let path = crate::repo_root().join("shell").join(name);
        if check {
            if fs::read_to_string(&path).unwrap_or_default() != generated {
                eprintln!("gen-shell: shell/{name} is out of date, run `cargo xtask gen-shell`");
                ok = false;
            }
        } else if let Err(error) = fs::write(&path, generated) {
            eprintln!("gen-shell: {}: {error}", path.display());
            ok = false;
        }
    }
    if ok {
        ExitCode::SUCCESS
    } else {
        ExitCode::FAILURE
    }
}

/// What takes the place of nvm's `__nvm` in `shell/bash_completion`: the
/// nvmimic program answers from one table (`nvmimic::complete`), so a TAB
/// starts one program and flags are suggested too. `@COMMANDS@` is nvm's own
/// list, filled in by [`completion`].
const COMPLETE: &str = r#"__nvm() {
  declare previous_word
  previous_word="${COMP_WORDS[COMP_CWORD - 1]}"

  # nvm's own completion sets COMMANDS and OPTIONS on its way and leaves
  # them set. The same happens here, in the same places.
  case "${previous_word}" in
    use | run | exec | ls | list | uninstall | alias | unalias) ;;
    *)
      COMMANDS='@COMMANDS@'
      if [ ${#COMP_WORDS[@]} != 4 ]; then
        case "${COMP_WORDS[COMP_CWORD]}" in
          -*) OPTIONS='' ;;
        esac
      fi
    ;;
  esac

  local IFS='
'
  # shellcheck disable=SC2207
  COMPREPLY=($(__nvmimic_handoff __nvm_complete bash "${COMP_CWORD}" "${COMP_WORDS[@]}"))

  # A flag that ends in `=` wants its value right behind it, with no space
  # in between. bash 4 and later can switch the space off for one answer.
  # bash 3.2 has no way to, so there the space stays.
  if [ "${#COMPREPLY[@]}" -eq 1 ]; then
    case "${COMPREPLY[0]-}" in
      *=) type compopt > /dev/null 2>&1 && compopt -o nospace ;;
    esac
  fi
  return 0
}"#;

/// Added after nvm's `complete` line.
const COMPLETE_MORE: &str = r#"complete -o default -F __nvm nvmimic

# zsh's own completion system can show a few words beside each suggestion,
# which `complete` has no way to pass on. Where that system is running, nvm
# and nvmimic are registered with it directly.
if [[ -n ${ZSH_NAME-} ]] && command -v compdef > /dev/null; then
  eval '_nvmimic_complete() {
    local -a suggestions
    suggestions=("${(@f)$(__nvmimic_handoff __nvm_complete zsh "$((CURRENT - 1))" "${words[@]}")}")
    suggestions=(${suggestions:#})
    (( $#suggestions )) || return 1
    # A flag that ends in `=` wants its value right behind it, so those
    # are added with nothing after them.
    local -a open
    open=(${(M)suggestions:#*=(|:*)})
    suggestions=(${suggestions:|open})
    _describe -V suggestion suggestions -- open -S ""
  }'
  compdef _nvmimic_complete nvm nvmimic
fi
"#;

/// nvm's bash_completion with its `__nvm` replaced by [`COMPLETE`]. nvm's
/// helper functions stay defined, since a shell that loaded the file has
/// them, and `__nvm_aliases` asks nvmimic instead of running `find` and
/// `sed`.
fn completion() -> Result<String, String> {
    let source = fs::read_to_string(crate::reference_dir().join("bash_completion"))
        .map_err(|e| e.to_string())?;
    let find = r#"    aliases="$(command cd "${NVM_DIR}/alias" && command find "${PWD}" -type f | command sed "s:${PWD}/::")""#;
    if !source.contains(find) {
        return Err("__nvm_aliases changed in nvm's bash_completion".to_string());
    }
    let source = source.replace(find, r#"    aliases="$(__nvmimic_handoff __nvm_aliases)""#);

    let changed = "nvm's bash_completion changed";
    let commands_at = source.find("COMMANDS='").ok_or(changed)? + "COMMANDS='".len();
    let commands_end = commands_at + source[commands_at..].find('\'').ok_or(changed)?;
    let commands = &source[commands_at..commands_end];
    let start = source.find("__nvm() {\n").ok_or(changed)?;
    let end = start + source[start..].find("\n}\n").ok_or(changed)? + "\n}".len();
    let register = "complete -o default -F __nvm nvm\n";
    if !source.ends_with(register) {
        return Err(changed.to_string());
    }
    let replaced = format!(
        "{}{}{}{COMPLETE_MORE}",
        &source[..start],
        COMPLETE.replace("@COMMANDS@", commands),
        &source[end..]
    );
    Ok(format!(
        "{}
# Changed by nvmimic: the nvmimic program works the suggestions out, flags
# included, and the `nvmimic` command is completed too. Generated by
# `cargo xtask gen-shell`.
{}",
        replaced.lines().take(3).collect::<Vec<_>>().join("\n"),
        replaced
            .lines()
            .skip(3)
            .map(|line| format!("{line}\n"))
            .collect::<String>()
    ))
}

/// The variables the binary reads from the shell, from the library's list.
fn forwarded() -> Result<Vec<String>, String> {
    Ok(nvmimic::host::FORWARDED
        .iter()
        .map(|name| name.to_string())
        .collect())
}

fn generate() -> Result<String, String> {
    let source =
        fs::read_to_string(crate::reference_dir().join("nvm.sh")).map_err(|e| e.to_string())?;
    let lines: Vec<&str> = source.split('\n').collect();

    // Every top-level function: its name and the lines from `name() {` to `}`.
    let mut functions: Vec<(&str, usize, usize)> = Vec::new();
    let mut i = 0;
    while i < lines.len() {
        if let Some(name) = lines[i].strip_suffix("() {")
            && name.chars().all(|c| c.is_ascii_lowercase() || c == '_')
        {
            let end = (i + 1..lines.len())
                .find(|&j| lines[j] == "}")
                .ok_or_else(|| format!("{name} has no closing brace"))?;
            functions.push((name, i, end));
            i = end;
        }
        i += 1;
    }
    let body = |name: &str| -> Result<String, String> {
        let (_, start, end) = functions
            .iter()
            .find(|(n, _, _)| *n == name)
            .ok_or_else(|| format!("nvm.sh has no function {name}"))?;
        Ok(lines[*start..=*end].join("\n"))
    };

    // nvmimic's functions, in the order `nvm.sh` defines them.
    let mut definitions: Vec<(&str, String)> = Vec::new();
    for name in VERBATIM {
        definitions.push((name, body(name)?));
    }

    let forwarded = forwarded()?;
    let set: String = forwarded.iter().map(|v| format!("${{{v}+ {v}}}")).collect();
    let values: Vec<String> = forwarded
        .iter()
        .map(|v| format!("__NVMIMIC_V_{v}=\"${{{v}-}}\""))
        .collect();
    let handoff = format!(
        r#"# `__nvmimic_handoff <function> [args]` runs one of nvm's functions in the
# nvmimic program. Its output goes straight to the terminal. What it changes
# in this shell comes back on file descriptor 8 as shell code, run here.
# This function is nvmimic's own and not part of nvm. Don't call it from your
# own scripts: it can change in any release. Each call tells the program
# which version of these functions the shell holds. After an update the
# program sends the new ones back the same way, and they are in place for
# the next call.
__nvmimic_handoff() {{
    local __nvmimic_name
    local __nvmimic_shell
    __nvmimic_shell=posix
    if [ -n "${{ZSH_VERSION-}}" ]; then
      __nvmimic_shell=zsh
    elif [ -n "${{BASH_VERSION-}}" ]; then
      case ":${{SHELLOPTS-}}:" in
        *:posix:*) __nvmimic_shell=bashposix ;;
        *) __nvmimic_shell=bash ;;
      esac
    fi
    # Two things only the shell can tell. nvm skips a checksum program whose
    # name is a shell alias, and `nvm debug` reports how the shell finds each
    # program it depends on. Both are looked up only for the commands that
    # use them.
    local __nvmimic_aliases
    __nvmimic_aliases=''
    local __nvmimic_info
    __nvmimic_info=''
    case "${{1-}}:${{2-}}" in
      nvm:install | nvm:i | nvm:debug | nvm_auto:install | nvm_*checksum*:* | nvm_download_artifact:* | nvm_install_*:*)
        for __nvmimic_name in {checksum_programs}; do
          if nvm_is_alias "${{__nvmimic_name}}"; then
            __nvmimic_aliases="${{__nvmimic_aliases}} ${{__nvmimic_name}}"
          fi
        done
      ;;
    esac
    case "${{1-}}:${{2-}}" in
      nvm:debug)
        for __nvmimic_name in {debug_tools}; do
          if nvm_has "${{__nvmimic_name}}"; then
            __nvmimic_info="${{__nvmimic_info}}${{__nvmimic_name}}
$(nvm_command_info "${{__nvmimic_name}}")
__nvmimic_end
"
          fi
        done
      ;;
    esac
    local __nvmimic_effects
    local __nvmimic_rc
    __nvmimic_rc=0
    {{ __nvmimic_effects="$(
      __NVMIMIC_SET="{set}" \
        {values} \
        __NVMIMIC_ALIASES="${{__nvmimic_aliases}}" \
        __NVMIMIC_COMMAND_INFO="${{__nvmimic_info}}" \
        __NVMIMIC_SHELL="${{__nvmimic_shell}}" \
        __NVMIMIC_ARG0="$0" \
        __NVMIMIC_SOURCE="${{BASH_SOURCE-}}" \
        __NVMIMIC_BASH="${{BASH_VERSINFO-}}" \
        __NVMIMIC_OPTS="$-" \
        __NVMIMIC_CACHE="@nvmimic-cache@" \
        __NVMIMIC_CODE="@nvmimic-version@" \
        __NVMIMIC_PROGRAM="@nvmimic-binary@" \
        __NVMIMIC_FD=8 \
        command "@nvmimic-binary@" __internal-shell-handoff "$@" 8>&1 1>&9 9>&-
    )" || __nvmimic_rc=$?; }} 9>&1
    eval "${{__nvmimic_effects}}"
    return "${{__nvmimic_rc}}"
}}"#,
        values = values.join(" \\\n        "),
        checksum_programs = nvmimic::nvm::checksum::PROGRAMS.join(" "),
        debug_tools = nvmimic::cmd::debug::TOOLS.join(" "),
    );

    // The body was written one level deeper than a function needs.
    let handoff: String = handoff
        .lines()
        .map(|line| format!("{}\n", line.strip_prefix("  ").unwrap_or(line)))
        .collect();
    definitions.push((HANDOFF, handoff.trim_end().to_string()));

    // nvm() keeps nvm's own handling of `set -e`, `set -a`, `set -E` and
    // IFS, ending at its closing `fi`, and then hands off. nvm finds the
    // default IFS with `tr`, which would start a program on every call.
    let (_, nvm_start, _) = functions
        .iter()
        .find(|(n, _, _)| *n == "nvm")
        .ok_or("nvm.sh has no nvm()")?;
    let ifs_branch = (nvm_start + 1..lines.len())
        .find(|&j| lines[j].contains(r#"elif [ "${IFS}" != "${DEFAULT_IFS}" ]; then"#))
        .ok_or("nvm() has no IFS handling")?;
    let preamble_end = (ifs_branch..lines.len())
        .find(|&j| lines[j] == "  fi")
        .ok_or("nvm() option handling is not closed")?;
    let preamble = lines[nvm_start + 1..=preamble_end].join("\n");
    let tr_ifs = "DEFAULT_IFS=\" $(nvm_echo t | command tr t \\\\t)\n\"";
    if !preamble.contains(tr_ifs) {
        return Err("nvm()'s DEFAULT_IFS line changed".to_string());
    }
    let preamble = preamble.replace(tr_ifs, "DEFAULT_IFS=' \t\n'");
    definitions.push((
        "nvm",
        format!(
            "{}\n{preamble}\n\n  {HANDOFF} nvm \"$@\"\n}}",
            lines[*nvm_start]
        ),
    ));
    definitions.push(("nvm_auto", AUTO.trim_end().to_string()));
    let handed_off = definitions.len();
    for (name, _, _) in &functions {
        if VERBATIM.contains(name) || *name == "nvm" || *name == "nvm_auto" {
            continue;
        }
        definitions.push((name, format!("{name}() {{ {HANDOFF} {name} \"$@\"; }}")));
    }

    let mut out = String::from(HEADER);
    for (index, (_, definition)) in definitions.iter().enumerate() {
        out.push_str(definition);
        // The one-line functions sit together, the others a line apart.
        out.push_str(if index >= handed_off { "\n" } else { "\n\n" });
    }
    out.push_str(nvmimic::install::LOAD_MARKER);
    out.push_str(TRACE_BACK);
    out.push('\n');

    // nvm's top-level code: NVM_CD_FLAGS and finding NVM_DIR.
    let top_start = lines
        .iter()
        .position(|line| *line == "# Make zsh glob matching behave same as bash")
        .ok_or("nvm.sh top-level block moved")?;
    let top_end = lines
        .iter()
        .position(|line| *line == "unset NVM_SCRIPT_SOURCE 2>/dev/null")
        .ok_or("nvm.sh top-level block moved")?;
    out.push_str(&lines[top_start..=top_end].join("\n"));
    // Loading ends with what this returns, as nvm's nvm.sh does. `init`
    // puts the switch to the default version in its place when it can.
    out.push_str("\n\n");
    out.push_str(nvmimic::init::SECOND_START);
    Ok(out)
}
