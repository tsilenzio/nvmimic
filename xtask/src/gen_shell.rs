//! `cargo xtask gen-shell`: writes the files in `shell/` from the pinned
//! nvm.sh. `--check` fails when one is out of date.
//!
//! `nvm.sh` defines every function nvm defines. Small pure-shell ones are
//! copied unchanged, `nvm` keeps nvm's own option handling, and the rest hand
//! their work to the binary through one private function,
//! `__nvmimic_handoff`. Nothing nvm does not have is reachable through the
//! name `nvm`.
//!
//! Some things only the calling shell can see: that one of nvm's functions
//! was replaced, that the install hook is a shell function, or that a
//! function has the name of a tool nvm runs. `__nvmimic_handoff` checks for
//! those on every call. When it finds one, it reads `nvm-functions.sh`, which holds
//! nvm's own functions, runs the call with them inside the caller's shell,
//! and then reads `nvmimic-functions.sh` to put nvmimic's functions back.
//! Both files skip the functions the caller replaced.

